#!/usr/bin/env bash
# Regenerate theme/presets/*.conf from the lyne-dots palettes. Dev only: the
# presets are committed, so the theme never needs lyne-dots at runtime.
#
#   tools/gen-presets.sh               # read ~/.lyne-dots/.data/themes
#   tools/gen-presets.sh -s DIR        # read another themes dir
#
# Each preset keeps only the palette keys theme.conf reads (no
# backgroundOpacity: it stays a separate choice). Presets whose JSON is gone
# are removed.
set -euo pipefail

repo=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
src=${LYNE_DOTS:-$HOME/.lyne-dots}/.data/themes
out=$repo/theme/presets
# Same order as theme.conf
keys=(background surface0 surface1 surface2 surface3 text textReverse subtext
    accent success warning error muted)

while getopts "s:h" opt; do
    case $opt in
    s) src=$OPTARG ;;
    *)
        sed -n '2,10p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
        [[ $opt == h ]] && exit 0 || exit 1
        ;;
    esac
done

command -v jq >/dev/null || { echo "missing: jq" >&2; exit 1; }
shopt -s nullglob
jsons=("$src"/*.json)
((${#jsons[@]})) || { echo "no themes in $src" >&2; exit 1; }

mkdir -p "$out"
trap 'rm -f "$out"/*.tmp' EXIT
declare -A seen=()
for json in "${jsons[@]}"; do
    id=$(basename "$json" .json)
    [[ $id =~ ^[a-z0-9-]+$ ]] || { echo "skipping $json: bad id" >&2; continue; }
    name=$(jq -r '.name // empty' "$json")
    {
        echo "[General]"
        echo "# Preset \"${name:-$id}\": the palette of the lyne-dots theme $id."
        echo "# Generated by tools/gen-presets.sh, don't edit."
        for key in "${keys[@]}"; do
            value=$(jq -r --arg k "$key" '.palette[$k] // empty' "$json")
            if [[ ! $value =~ ^#([0-9a-fA-F]{6}|[0-9a-fA-F]{8})$ ]]; then
                echo "$json: palette.$key is missing or not a color: '$value'" >&2
                exit 1
            fi
            echo "$key=$value"
        done
    } >"$out/$id.conf.tmp"
    mv "$out/$id.conf.tmp" "$out/$id.conf"
    seen[$id]=1
done

for conf in "$out"/*.conf; do
    id=$(basename "$conf" .conf)
    [[ -n ${seen[$id]:-} ]] && continue
    rm "$conf"
    echo "removed $id (no $id.json)"
done

echo "${#seen[@]} presets in ${out#"$repo"/}: $(printf '%s\n' "${!seen[@]}" | sort | xargs)"
